// Fits the Ghost side profile to the reference model using the real engine.
//   FIT_SIDE=1 npx vitest run tests/fitSide.test.ts   -> rewrites src/params/side.generated.ts
// Without FIT_SIDE it only verifies the checked-in fit stays close to the reference.
import { describe, it, expect } from 'vitest';
import fs from 'node:fs';
import { ShapeEngine } from '../src/geometry/engine';
import { PRESETS, presetParams } from '../src/params/presets';
import { clampOutline } from '../src/params/outline';
import { SIDE_N, SIDE_MIN, SIDE_MAX, SideProfile, defaultSide } from '../src/params/side';
import { REFERENCE_SCALE } from '../src/params/core';
import { GHOST_FIT } from '../src/params/presets.generated';
import { SideCurve } from '../src/geometry/profile';

const eng = new ShapeEngine();
const ref: number[][] = fs.readFileSync('reference/charmer-body.obj', 'utf8').split('\n').filter((l) => l.startsWith('v '))
  .map((l) => l.trim().split(/\s+/).slice(1, 4).map((x) => +x * REFERENCE_SCALE));
const refH = Math.max(...ref.map((v) => v[1]));
const YN = Array.from({ length: 22 }, (_, i) => 0.08 + i * 0.04); // sample heights (fractions)

function extents(verts: ArrayLike<number>[], H: number, zOff: number) {
  return YN.map((yn) => {
    const y = yn * H;
    const b = verts.filter((v) => Math.abs(v[1] - y) < 1.2); // a flat 2D side view: every point of the body counts, wherever it sits across the width
    if (!b.length) return { f: NaN, b: NaN };
    return { f: Math.max(...b.map((v) => v[2])) - zOff, b: Math.min(...b.map((v) => v[2])) - zOff };
  });
}
const refExt = extents(ref, refH, GHOST_FIT.zEq);
const FIT_MIN = 0.45; // fitted values never go thinner than this (keeps walls buildable)
// The puck plateau is flat by design, so the front there cannot follow the reference belly: leave it out of the front fit.
const PLATEAU_MM = 0; // the flat core seat is off by default, so the front is fitted everywhere
let cyMm = 25;
(() => { const g = PRESETS[0], p = presetParams(g); const cage = new Float32Array(eng.qs.vertCount * 3); cyMm = eng.buildCage(clampOutline(g.outline, p.wall), p, cage)!.shiftY; })();
// low down the front is deliberately kept fuller than the reference so the Core recess stays inside the body (see presets.ts)
const frontMasked = (i: number) => YN[i] < 0.22 || Math.abs(YN[i] * refH - cyMm) < PLATEAU_MM;

function modelExt(side: SideProfile) {
  const g = PRESETS[0], p = { ...presetParams(g), side }, o = clampOutline(g.outline, p.wall);
  const cage = new Float32Array(eng.qs.vertCount * 3);
  eng.buildCage(o, p, cage);
  const pos = new Float32Array(eng.smoothVertCount(2) * 3); eng.smoothInto(cage, 2, pos);
  const v: number[][] = []; for (let i = 0; i < pos.length; i += 3) v.push([pos[i], pos[i + 1], pos[i + 2]]);
  const H = Math.max(...v.map((q) => q[1]));
  return extents(v, H, 0);
}
const err = (side: SideProfile) => {
  const m = modelExt(side); let worst = 0;
  m.forEach((e, i) => { if (Number.isFinite(e.f) && Number.isFinite(refExt[i].f)) worst = Math.max(worst, frontMasked(i) ? 0 : Math.abs(e.f - refExt[i].f), Math.abs(e.b - refExt[i].b)); });
  return worst;
};
const interp = (xs: number[], ys: number[], x: number) => {
  if (x <= xs[0]) return ys[0]; if (x >= xs[xs.length - 1]) return ys[ys.length - 1];
  let i = 0; while (xs[i + 1] < x) i++;
  return ys[i] + ((ys[i + 1] - ys[i]) * (x - xs[i])) / (xs[i + 1] - xs[i]);
};

describe('side profile fit', () => {
  if (process.env.FIT_SIDE) {
    it('fits and writes side.generated.ts', () => {
      let side = defaultSide();
      const base = err(side);
      for (let it = 0; it < 14; it++) {
        const m = modelExt(side);
        const ratio = (key: 'f' | 'b') => YN.map((_, i) => (!(key === 'f' && frontMasked(i)) && Number.isFinite(m[i][key]) && Math.abs(m[i][key]) > 0.3 ? Math.min(3, Math.max(0.33, refExt[i][key] / m[i][key])) : 1));
        const rf = ratio('f'), rb = ratio('b');
        const upd = (arr: number[], r: number[]) => arr.map((k, i) => Math.min(SIDE_MAX, Math.max(Math.max(SIDE_MIN, FIT_MIN), k * Math.pow(interp(YN, r, i / (SIDE_N - 1)), 0.7))));
        side = { front: upd(side.front, rf), back: upd(side.back, rb) };
      }
      const after = err(side);
      const mm = modelExt(side);
      console.log('per-height error (yn: front/back mm):', YN.map((yn, i) => `${yn.toFixed(2)}:${frontMasked(i) ? '-' : (mm[i].f - refExt[i].f).toFixed(1)}/${(mm[i].b - refExt[i].b).toFixed(1)}`).join('  '));
      console.log('side fit: max error before', base.toFixed(2), 'mm, after', after.toFixed(2), 'mm\nback ', side.back.map((x) => x.toFixed(2)).join(' '), '\nfront', side.front.map((x) => x.toFixed(2)).join(' '));
      const r = (a: number[]) => a.map((x) => +x.toFixed(3));
      fs.writeFileSync('src/params/side.generated.ts',
        `// GENERATED by tests/fitSide.test.ts (FIT_SIDE=1). Do not edit by hand.\nexport const SIDE_FIT = ${JSON.stringify({ back: r(side.back), front: r(side.front), maxErrorMm: +after.toFixed(2) })} as const;\n`);
      expect(after).toBeLessThan(base);
    });
  } else {
    it('checked-in fit stays within 3 mm of the reference side profile', () => {
      const g = presetParams(PRESETS[0]);
      expect(err(g.side)).toBeLessThan(3);
      // and the curve itself is sane
      const c = new SideCurve(g.side.back); for (let t = 0; t <= 1; t += 0.05) expect(Number.isFinite(c.eval(t))).toBe(true);
    });
  }
});
